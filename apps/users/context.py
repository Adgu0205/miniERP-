def nav_context(request):
    user = getattr(request, "user", None)
    path = request.path
    items = []
    if user and user.is_authenticated:
        for module, label, urlname, icon, prefix in NAV:
            if has_module(user, module):
                items.append({"label": label, "urlname": urlname, "icon": icon,
                              "module": module, "prefix": prefix})
    # Longest matching prefix wins → only one item highlighted.
    best = None
    for it in items:
        if it["prefix"] == "/":
            if path == "/":
                best = it["prefix"]
        elif path.startswith(it["prefix"]):
            if best is None or len(it["prefix"]) > len(best):
                best = it["prefix"]
    for it in items:
        it["active"] = (it["prefix"] == best)
    return {"nav_items": items}
